/**
 * Agent execution simulator.
 *
 * Given a ready task, this picks the best-matching agent from the owning team,
 * "runs" it through the LLM adapter, generates realistic code artifacts, updates
 * agent/team statistics and emits live events. It is the concrete work unit the
 * scheduler dispatches to the worker pool.
 */

import { nanoid } from 'nanoid'
import { store } from '../state'
import { bus } from './eventBus'
import { logger } from '../observability/logger'
import { tracing } from '../observability/tracing'
import { getLlmProvider } from './llmAdapter'
import { searchVectors } from './knowledgeService'
import { artifactRepo } from '../db/repositories/knowledgeRepo'
import { AVG_BYTES_PER_LINE } from '@shared/constants'
import type { Agent, CodeArtifact, Run, Task } from '@shared/types'

export interface ExecResult {
  ok: boolean
  agentId: string
  tokensUsed: number
  artifacts: CodeArtifact[]
  linesOfCode: number
  durationMs: number
  error?: string
}

/** Map team kind → a representative language + file extension for artifacts. */
const LANG_BY_TEAM: Record<string, { lang: string; ext: string; dir: string }> = {
  backend: { lang: 'TypeScript', ext: 'ts', dir: 'src/server' },
  frontend: { lang: 'TypeScript React', ext: 'tsx', dir: 'src/web' },
  data: { lang: 'Python', ext: 'py', dir: 'pipelines' },
  devops: { lang: 'YAML', ext: 'yml', dir: 'infra' },
  security: { lang: 'Markdown', ext: 'md', dir: 'security' },
  qa: { lang: 'TypeScript', ext: 'test.ts', dir: 'tests' },
  research: { lang: 'Markdown', ext: 'md', dir: 'docs/rfc' },
  design: { lang: 'CSS', ext: 'css', dir: 'src/web/styles' },
  integration: { lang: 'TypeScript', ext: 'ts', dir: 'src/integrations' },
  docs: { lang: 'Markdown', ext: 'md', dir: 'docs' },
}

/** Pick the most suitable idle agent on the team for this task. */
function pickAgent(teamId: string, requiredSkills: string[]): Agent | null {
  const agents = store.agentsOfTeam(teamId).filter((a) => a.role !== 'supervisor')
  if (agents.length === 0) return null
  // Score by skill overlap, then prefer idle agents with higher success rate.
  const scored = agents
    .map((a) => {
      const overlap = a.skills.filter((s) => requiredSkills.includes(s)).length
      const idleBonus = a.status === 'idle' ? 2 : 0
      return { a, score: overlap * 3 + idleBonus + a.stats.successRate }
    })
    .sort((x, y) => y.score - x.score)
  return scored[0].a
}

function slug(title: string): string {
  return title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '').slice(0, 40)
}

/** Generate 1–4 plausible artifacts for a finished task. */
function generateArtifacts(run: Run, task: Task, agent: Agent): CodeArtifact[] {
  const cfg = LANG_BY_TEAM[task.teamKind] ?? LANG_BY_TEAM.backend
  const fileCount = 1 + Math.floor(Math.random() * 3)
  const base = slug(task.title)
  const artifacts: CodeArtifact[] = []
  for (let i = 0; i < fileCount; i++) {
    const lines = 60 + Math.floor(Math.random() * 320)
    const name = i === 0 ? base : `${base}-${i + 1}`
    const path = `${cfg.dir}/${name}.${cfg.ext}`
    const preview =
      `// ${task.title}\n// Generated by agent ${agent.name} (${agent.role}) on team ${task.teamKind}.\n` +
      `// Part ${i + 1}/${fileCount} — ~${lines} lines.\n`
    artifacts.push({
      id: `art_${nanoid(8)}`,
      runId: run.id,
      path,
      language: cfg.lang,
      lines,
      bytes: lines * AVG_BYTES_PER_LINE,
      taskId: task.id,
      preview,
      createdAt: Date.now(),
    })
  }
  return artifacts
}

/** Execute a single task with the best agent on its team. */
export async function executeTask(run: Run, task: Task): Promise<ExecResult> {
  const team = store.teamByKind(task.teamKind)
  if (!team) {
    return { ok: false, agentId: '', tokensUsed: 0, artifacts: [], linesOfCode: 0, durationMs: 0, error: `no team for ${task.teamKind}` }
  }
  const agent = pickAgent(team.id, task.requiredSkills)
  if (!agent) {
    return { ok: false, agentId: '', tokensUsed: 0, artifacts: [], linesOfCode: 0, durationMs: 0, error: 'no available agent' }
  }

  const span = tracing.start(run.id, `agent:${agent.name}:${task.title}`, null, { team: task.teamKind, role: agent.role })
  const started = Date.now()

  // Mark agent + task busy.
  agent.status = 'busy'
  agent.currentTaskId = task.id
  store.setAgent(agent)
  bus.emit('agent.updated', agent, run.id)
  logger.info(`team:${team.kind}`, `${agent.name} picked up "${task.title}"`, run.id)

  // Retrieve grounding context (RAG) before acting.
  const context = searchVectors(task.title + ' ' + task.description, 3).map((h) => h.doc.text)

  // "Think" via the adapter (simulated by default).
  const provider = getLlmProvider()
  const res = await provider.complete(
    { role: agent.role, prompt: `${task.title}\n${task.description}`, context, maxTokens: 200 + task.estimateMs / 8 },
    agent.model,
  )

  // Simulate compute time proportional to the estimate (compressed for demo speed).
  await sleep(Math.min(900, Math.round(task.estimateMs / 6) + res.latencyMs / 4))

  // Small, deterministic-ish failure chance so validators/reviewers have teeth.
  const failed = Math.random() < failureChance(agent, task)

  const artifacts = failed ? [] : generateArtifacts(run, task, agent)
  const lines = artifacts.reduce((s, a) => s + a.lines, 0)
  for (const a of artifacts) {
    store.setArtifact(a)
    try {
      artifactRepo.insert(a)
    } catch {
      /* best effort */
    }
  }

  const durationMs = Date.now() - started

  // Update agent stats.
  if (failed) {
    agent.stats.tasksFailed++
    agent.status = 'idle'
  } else {
    agent.stats.tasksCompleted++
    agent.status = 'idle'
    team.completedTasks++
    store.setTeam(team)
  }
  agent.stats.tokensUsed += res.tokensIn + res.tokensOut
  agent.stats.avgDurationMs = Math.round((agent.stats.avgDurationMs + durationMs) / 2)
  const total = agent.stats.tasksCompleted + agent.stats.tasksFailed
  agent.stats.successRate = total ? agent.stats.tasksCompleted / total : 1
  agent.currentTaskId = null
  store.setAgent(agent)
  bus.emit('agent.updated', agent, run.id)

  tracing.end(span, failed ? 'error' : 'ok', { tokens: res.tokensIn + res.tokensOut, lines })
  if (failed) logger.warn(`team:${team.kind}`, `${agent.name} hit an error on "${task.title}" — will retry`, run.id)
  else logger.info(`team:${team.kind}`, `${agent.name} completed "${task.title}" (+${lines} LoC)`, run.id)

  return {
    ok: !failed,
    agentId: agent.id,
    tokensUsed: res.tokensIn + res.tokensOut,
    artifacts,
    linesOfCode: lines,
    durationMs,
    error: failed ? 'simulated execution error' : undefined,
  }
}

/** Higher-attempt tasks and lower-success agents fail a little more often. */
function failureChance(agent: Agent, task: Task): number {
  const base = 0.08
  const skillPenalty = agent.skills.some((s) => task.requiredSkills.includes(s)) ? 0 : 0.06
  const fatigue = agent.stats.successRate < 0.8 ? 0.05 : 0
  return Math.min(0.28, base + skillPenalty + fatigue) * (task.attempts > 0 ? 0.4 : 1)
}

function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms))
}
